import { readFile, readdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import postcss from "postcss";
import selectorParser from "postcss-selector-parser";
const root = resolve(import.meta.dirname, "..");
function classNames(css) {
  const classes = new Set();
  postcss.parse(css).walkRules((rule) => {
    selectorParser((selectors) =>
      selectors.walkClasses((node) => classes.add(node.value)),
    ).processSync(rule.selector);
  });
  return classes;
}
const bootstrap = classNames(
  await readFile(resolve(root, "node_modules/bootstrap/dist/css/bootstrap.css"), "utf8"),
);
let report =
  "# Bootstrap selector inventory\n\nGenerated by `frontend/scripts/audit-theme-selectors.mjs`. These classes are\ncompatibility candidates, not semantic tokens. Framework-generated markup means\nabsence of literal source references cannot establish dead CSS. Includes the\nRemuage companion files; retain rules until their consumers migrate.\n\n";
async function themeFiles(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      const relative = prefix + entry.name;
      return entry.isDirectory()
        ? themeFiles(resolve(directory, entry.name), relative + "/")
        : entry.name.endsWith(".css")
          ? [relative]
          : [];
    }),
  );
  return files.flat();
}
for (const file of (await themeFiles(resolve(root, "public/themes"))).sort()) {
  const classes = classNames(await readFile(resolve(root, "public/themes", file), "utf8"));
  const overrides = [...classes].filter((name) => bootstrap.has(name)).sort();
  report += `## ${file}\n\n${overrides.map((name) => `\`${name}\``).join(", ") || "No Bootstrap class overrides."}\n\n`;
}
await writeFile(resolve(root, "../docs/decisions/1105-theme-selector-audit.md"), report);
